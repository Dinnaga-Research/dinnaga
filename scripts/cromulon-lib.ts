// ABOUTME: Pure functions for the Cromulon frame converter: luminance, normalise, resample, quantise, encode.
// ABOUTME: Kept apart from the CLI so vitest can import them without spawning anything.
import { PNG } from 'pngjs';

/** Rec. 709 luminance of 0..255 channels, as 0..1. */
export function luminance(r: number, g: number, b: number): number {
  return (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;
}

/** Scale to 0..1 against the data's own min/max, or against black/white when given. Clamped. */
export function normalise(values: ArrayLike<number>, black?: number, white?: number): Float32Array {
  const n = values.length;
  let lo = black;
  let hi = white;
  if (lo === undefined || hi === undefined) {
    let mn = Infinity;
    let mx = -Infinity;
    for (let i = 0; i < n; i++) {
      mn = Math.min(mn, values[i]!);
      mx = Math.max(mx, values[i]!);
    }
    lo ??= mn;
    hi ??= mx;
  }
  const span = hi - lo;
  const out = new Float32Array(n);
  for (let i = 0; i < n; i++) {
    out[i] = span > 0 ? Math.max(0, Math.min(1, (values[i]! - lo) / span)) : 0;
  }
  return out;
}

/** Area-average resample of a w x h grid to outW x outH (fractional pixel coverage is weighted). */
export function resample(values: ArrayLike<number>, w: number, h: number, outW: number, outH: number): Float32Array {
  const out = new Float32Array(outW * outH);
  for (let r = 0; r < outH; r++) {
    const y0 = (r * h) / outH;
    const y1 = ((r + 1) * h) / outH;
    for (let c = 0; c < outW; c++) {
      const x0 = (c * w) / outW;
      const x1 = ((c + 1) * w) / outW;
      let sum = 0;
      let weight = 0;
      for (let y = Math.floor(y0); y < Math.min(h, Math.ceil(y1)); y++) {
        const wy = Math.min(y + 1, y1) - Math.max(y, y0);
        for (let x = Math.floor(x0); x < Math.min(w, Math.ceil(x1)); x++) {
          const wx = Math.min(x + 1, x1) - Math.max(x, x0);
          sum += values[y * w + x]! * wx * wy;
          weight += wx * wy;
        }
      }
      out[r * outW + c] = weight > 0 ? sum / weight : 0;
    }
  }
  return out;
}

/** 0..1 to 16 levels; level 0 (empty) exactly where v < 1/16. */
export function quantise(values: ArrayLike<number>): Uint8Array {
  const out = new Uint8Array(values.length);
  for (let i = 0; i < values.length; i++) out[i] = Math.max(0, Math.min(15, Math.floor(values[i]! * 16)));
  return out;
}

/** One hex digit per level. */
export function encodeHex(levels: Uint8Array): string {
  let s = '';
  for (const l of levels) s += l.toString(16);
  return s;
}

export interface Crop {
  x: number;
  y: number;
  w: number;
  h: number;
}

export interface ConvertOptions {
  crop?: Crop;
  black?: number;
  white?: number;
  width: number;
}

export interface Converted {
  width: number;
  height: number;
  levels: Uint8Array;
}

/** Size of the image after the optional crop. */
export function croppedSize(png: PNG, crop?: Crop): { w: number; h: number } {
  return crop ? { w: crop.w, h: crop.h } : { w: png.width, h: png.height };
}

/** crop -> luminance -> normalise -> area-average to `width` -> 16 levels. */
export function convertPng(png: PNG, o: ConvertOptions): Converted {
  const { x, y, w, h } = o.crop ?? { x: 0, y: 0, w: png.width, h: png.height };
  if (x < 0 || y < 0 || w <= 0 || h <= 0 || x + w > png.width || y + h > png.height) {
    throw new Error(`crop ${x},${y},${w},${h} is outside the ${png.width}x${png.height} image`);
  }
  const lum = new Float32Array(w * h);
  for (let r = 0; r < h; r++) {
    for (let c = 0; c < w; c++) {
      const i = ((y + r) * png.width + (x + c)) * 4;
      lum[r * w + c] = luminance(png.data[i]!, png.data[i + 1]!, png.data[i + 2]!);
    }
  }
  const norm = normalise(lum, o.black, o.white);
  const outH = Math.max(1, Math.round((h * o.width) / w));
  return { width: o.width, height: outH, levels: quantise(resample(norm, w, h, o.width, outH)) };
}

/** The generated data module's source. */
export function emitModule(width: number, height: number, open: Uint8Array, closed?: Uint8Array): string {
  const parts = [`version: 1`, `width: ${width}`, `height: ${height}`, `open: '${encodeHex(open)}'`];
  if (closed) parts.push(`closed: '${encodeHex(closed)}'`);
  return (
    '// GENERATED by `bun run cromulon:convert` from an operator-supplied frame. Source image not in git. Do not edit.\n' +
    `export const CROMULON_FRAME = { ${parts.join(', ')} };\n`
  );
}

const RAMP = ' .:-=+*#%@';

/** An 80-column classic-ramp preview of a level grid (cells are about twice as tall as wide). */
export function preview(levels: Uint8Array, width: number, height: number, cols = 80): string {
  const rows = Math.max(1, Math.round((height * cols) / width / 2));
  const avg = resample(levels, width, height, cols, rows);
  let s = '';
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      s += RAMP[Math.min(RAMP.length - 1, Math.round((avg[r * cols + c]! / 15) * (RAMP.length - 1)))];
    }
    s += '\n';
  }
  return s;
}
