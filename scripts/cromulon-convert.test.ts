// ABOUTME: Tests for the Cromulon frame converter: the pure pipeline functions and the CLI end to end.
// ABOUTME: Uses only synthetic images made in memory or in a temp dir; never a real frame.
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, existsSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { PNG } from 'pngjs';
import { afterAll, describe, expect, it } from 'vitest';
import { decodeHex } from '../src/components/cromulon/frame';
import { encodeHex, luminance, normalise, quantise, resample } from './cromulon-lib';

const ROOT = resolve(__dirname, '..');
const SCRIPT = join(ROOT, 'scripts', 'cromulon-convert.ts');
const tmp = mkdtempSync(join(tmpdir(), 'cromulon-test-'));
afterAll(() => rmSync(tmp, { recursive: true, force: true }));

/** A shaded circle on black, w x h, as a PNG file. */
function writeCircle(file: string, w: number, h: number) {
  const png = new PNG({ width: w, height: h });
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const d = Math.hypot(x - w / 2, y - h / 2) / (h / 2.5);
      const v = d < 1 ? Math.round(255 * (1 - d * 0.8)) : 0;
      const i = (y * w + x) * 4;
      png.data[i] = v;
      png.data[i + 1] = v;
      png.data[i + 2] = v;
      png.data[i + 3] = 255;
    }
  }
  writeFileSync(file, PNG.sync.write(png));
}

function run(args: string[]) {
  return spawnSync('bun', [SCRIPT, ...args], { cwd: ROOT, encoding: 'utf8' });
}

describe('converter pure functions', () => {
  it('computes Rec. 709 luminance', () => {
    expect(luminance(255, 255, 255)).toBeCloseTo(1, 5);
    expect(luminance(0, 0, 0)).toBe(0);
    expect(luminance(255, 0, 0)).toBeCloseTo(0.2126, 4);
    expect(luminance(0, 255, 0)).toBeCloseTo(0.7152, 4);
    expect(luminance(0, 0, 255)).toBeCloseTo(0.0722, 4);
  });

  it('normalises to the frame min/max, or to --black/--white when given', () => {
    expect(Array.from(normalise([0.2, 0.4, 0.6]))).toEqual([0, 0.5, 1].map((v) => expect.closeTo(v, 5)));
    const out = normalise([0.1, 0.5, 0.9], 0.3, 0.7);
    expect(out[0]).toBe(0);
    expect(out[1]).toBeCloseTo(0.5, 5);
    expect(out[2]).toBe(1);
    expect(Array.from(normalise([0.5, 0.5]))).toEqual([0, 0]); // flat image: no divide by zero
  });

  it('area-averages a resample', () => {
    // 4x2 -> 2x1: each output is the mean of a 2x2 block.
    const out = resample([0, 1, 0.5, 0.5, 1, 0, 0.5, 0.5], 4, 2, 2, 1);
    expect(out[0]).toBeCloseTo(0.5, 5);
    expect(out[1]).toBeCloseTo(0.5, 5);
    // Fractional boundaries: 3x1 -> 2x1 weights the middle pixel half to each side.
    const f = resample([0, 1, 0], 3, 1, 2, 1);
    expect(f[0]).toBeCloseTo((0 + 0.5) / 1.5, 5);
    expect(f[1]).toBeCloseTo(0.5 / 1.5, 5);
  });

  it('quantises to 16 levels with level 0 exactly where v < 1/16', () => {
    expect(Array.from(quantise([0, 0.0624, 0.0625, 0.5, 0.999, 1]))).toEqual([0, 0, 1, 8, 15, 15]);
  });

  it('gives the expected levels for a 4x4 synthetic image', () => {
    const lum = Array.from({ length: 16 }, (_, i) => i / 15); // already spans 0..1
    const levels = quantise(resample(normalise(lum), 4, 4, 4, 4));
    expect(Array.from(levels)).toEqual(lum.map((v) => Math.min(15, Math.floor(v * 16))));
    // Only index 0 (v = 0) is empty: index 1 has v = 0.0667 >= 1/16.
    expect(Array.from(levels).filter((l) => l === 0)).toHaveLength(1);
  });

  it('round-trips hex encode and decode', () => {
    const levels = Uint8Array.from([0, 1, 9, 10, 15, 7, 0]);
    const hex = encodeHex(levels);
    expect(hex).toBe('019af70');
    expect(Array.from(decodeHex(hex))).toEqual(Array.from(levels));
  });
});

describe('.gitignore', () => {
  it('lists cromulon-src/', () => {
    const lines = readFileSync(join(ROOT, '.gitignore'), 'utf8').split('\n').map((l) => l.trim());
    expect(lines).toContain('cromulon-src/');
  });
});

describe('converter CLI', () => {
  it('converts a 320x240 PNG to a 160x120 module with no closed key', () => {
    const png = join(tmp, 'a.png');
    const out = join(tmp, 'a-frame.ts');
    writeCircle(png, 320, 240);
    const r = run(['--open', png, '--out', out]);
    expect(r.status).toBe(0);
    expect(r.stdout.length).toBeGreaterThan(0); // the ASCII preview
    const src = readFileSync(out, 'utf8');
    expect(src).toMatch(/^\/\/ GENERATED by `bun run cromulon:convert`/);
    const open = /open: '([0-9a-f]*)'/.exec(src)![1]!;
    expect(src).toMatch(/width: 160/);
    expect(src).toMatch(/height: 120/);
    expect(open.length).toBe(19200);
    expect(src).not.toMatch(/closed/);
  });

  it('emits closed when --closed has the same size, and exits non-zero when the sizes differ', () => {
    const a = join(tmp, 'b-open.png');
    const same = join(tmp, 'b-closed.png');
    const other = join(tmp, 'b-other.png');
    writeCircle(a, 320, 240);
    writeCircle(same, 320, 240);
    writeCircle(other, 200, 200);
    const out = join(tmp, 'b-frame.ts');
    const ok = run(['--open', a, '--closed', same, '--out', out]);
    expect(ok.status).toBe(0);
    expect(readFileSync(out, 'utf8')).toMatch(/closed: '[0-9a-f]{19200}'/);
    const bad = join(tmp, 'b-bad.ts');
    const r = run(['--open', a, '--closed', other, '--out', bad]);
    expect(r.status).not.toBe(0);
    expect(existsSync(bad)).toBe(false);
  });

  it('refuses an input under src/ or public/', () => {
    for (const dir of ['src', 'public']) {
      const r = run(['--open', `${dir}/nope.png`, '--out', join(tmp, 'x.ts')]);
      expect(r.status).not.toBe(0);
      expect(r.stderr).toMatch(/refus/i);
    }
  });

  it('refuses a git-tracked input', () => {
    const r = run(['--open', 'package.json', '--out', join(tmp, 'y.ts')]);
    expect(r.status).not.toBe(0);
    expect(r.stderr).toMatch(/tracked/i);
  });
});
