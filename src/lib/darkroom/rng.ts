// ABOUTME: mulberry32: the small seeded generator behind every frame (C uses seed 7193 for the scene,
// ABOUTME: 99 for the grain tile). Deterministic; no Math.random anywhere in the painter.

export type Rng = () => number;

export function mulberry32(seed: number): Rng {
  let s = seed | 0;
  return () => {
    s = (s + 0x6d2b79f5) | 0;
    let t = Math.imul(s ^ (s >>> 15), 1 | s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
